let age = "16" 
console.log(typeof age)     // Output: string

age = Number(age)
console.log(typeof age)     // Output: number


let f_age = 45
console.log(typeof f_age)   // Output: number

f_age = String(f_age)
console.log(typeof f_age)   // Output: string
